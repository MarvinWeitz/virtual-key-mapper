"""OpenCode with a generated plugin that adds a fresh credential and the folder's labels to each request.

The plugin (OpenCode v1 ``chat.headers`` hook, verified with 1.18.34) runs ``vkm token --json``
and ``repo show --json --launch`` for the directory OpenCode works in (``--launch``: the labels of
``run opencode --label`` count as explicit), replaces the provider's placeholder key, refuses to send
the credential to any other base URL, and fails the request while required labels are missing.
``setup opencode`` registers it with a provider in the global config; ``run opencode`` passes the
same through OPENCODE_CONFIG_CONTENT. OpenCode v2 has a different plugin API: ``run`` keeps its
previous launch-time token there, and ``setup`` refuses.
"""

import json
import os
import re
import shutil
import subprocess
from pathlib import Path
from typing import Mapping

from ..adapters import Api, IntegrationContext
from ..errors import CredentialError
from ..labels import Attribution
from ..models import list_models
from ..profiles import atomic_write_text
from .common import TOKEN_VARIABLE, attribution_headers, child_environment, execute, set_launch_marker

PROVIDER = "vkm"
PLACEHOLDER_KEY = "vkm-plugin-sets-the-credential"

PLUGIN = """// Generated by vkm; regenerated by 'vkm setup opencode' and 'run opencode'.
// Adds a fresh gateway credential and the labels of OpenCode's directory to each request of one provider.
import { execFile } from "node:child_process";

const SETTINGS = __SETTINGS__;
const resolved = new Map();
let token = null;

function cli(args) {
  return new Promise((resolve, reject) => {
    execFile(SETTINGS.cli[0], [...SETTINGS.cli.slice(1), ...args], { windowsHide: true, maxBuffer: 1 << 20 },
      (error, stdout, stderr) => error
        ? reject(new Error(String(stderr || error.message).replace(/^Error: /, "").trim()))
        : resolve(JSON.parse(stdout)));
  });
}

async function credential() {
  const now = Date.now() / 1000;
  const until = token && Math.min(token.fetched + 240, token.expires_at === null ? Infinity : token.expires_at - 60);
  if (!token || now >= until) {
    token = { ...(await cli(["token", "--json", "--profile", SETTINGS.profile])), fetched: now };
  }
  return token.access_token;
}

async function attribution(directory) {
  const cached = resolved.get(directory);
  if (cached && Date.now() - cached.at < 30000) return cached.value;
  // --launch: the --label values of 'run opencode' (VKM_LAUNCH_LABELS) count as explicit.
  const value = await cli(["repo", "show", "--json", "--launch", "--profile", SETTINGS.profile, "--directory", directory]);
  resolved.set(directory, { at: Date.now(), value });
  return value;
}

const trimmed = (url) => String(url || "").replace(/\\/+$/, "");

export const Vkm = async ({ directory }) => ({
  "chat.headers": async (input, output) => {
    if (input?.model?.providerID !== SETTINGS.provider) return;
    const baseURL = trimmed(input?.provider?.options?.baseURL);
    if (baseURL !== trimmed(SETTINGS.baseURL)) {
      throw new Error(`vkm: refusing to send the credential to ${baseURL || "an unknown URL"}.`);
    }
    const shown = await attribution(directory);
    // Fail closed: without every required label (or with headers vkm could not build) nothing is sent.
    if (shown?.complete !== true || typeof shown.headers !== "object" || shown.headers === null) {
      throw new Error(`vkm: ${shown?.message || "the labels for " + directory + " are incomplete"}`);
    }
    // Every header vkm can send is replaced, so one this request omits cannot survive from an earlier plugin.
    const ours = new Set(SETTINGS.headers.map((name) => name.toLowerCase()));
    for (const name of Object.keys(output.headers)) {
      if (ours.has(name.toLowerCase())) delete output.headers[name];
    }
    Object.assign(output.headers, shown.headers, { Authorization: "Bearer " + (await credential()) });
  },
});
"""


def _opencode_command(args: list[str], major: int = 1) -> list[str]:
    if args and args[0] == "exec":
        raise CredentialError("OpenCode uses 'run', not Codex's 'exec': opencode -- run \"Your prompt\".")
    flag_args = args[:args.index("--")] if "--" in args else args
    if any(
        arg in ("--server", "--attach") or arg.startswith(("--server=", "--attach="))
        for arg in flag_args
    ):
        raise CredentialError("OpenCode sessions cannot attach to a shared server; it would bypass label/credential isolation.")
    if major == 1:
        return ["opencode", *args]
    if major != 2:
        raise CredentialError("Supported OpenCode versions are v1 and v2; this version needs an updated adapter.")
    if any(arg.startswith("--standalone=") and arg != "--standalone=true" for arg in flag_args):
        raise CredentialError("The OpenCode v2 launcher cannot disable its private server.")
    if args and args[0] == "run":
        return ["opencode", "run", "--standalone", *args[1:]]
    if args and not args[0].startswith("-") and not os.path.isdir(args[0]):
        raise CredentialError(
            "OpenCode v2 launch mode supports interactive use or 'run'. "
            "Use the unwrapped OpenCode command for other subcommands."
        )
    return ["opencode", "--standalone", *args]


def _opencode_major(executable: str) -> int:
    try:
        result = subprocess.run(
            [executable, "--version"], capture_output=True, text=True, timeout=10, check=False
        )
    except (OSError, subprocess.TimeoutExpired, UnicodeError):
        raise CredentialError("Cannot check OpenCode's version; verify 'opencode --version' works.") from None
    match = re.fullmatch(
        r"(?:opencode\s+)?v?(\d+)\.\d+\.\d+(?:[-+][A-Za-z0-9.-]+)?",
        result.stdout.strip(),
        re.IGNORECASE,
    )
    if result.returncode != 0 or match is None:
        raise CredentialError("Cannot identify OpenCode's version; verify 'opencode --version' works.")
    return int(match[1])


def config_path(environ: Mapping[str, str] | None = None) -> Path:
    environ = os.environ if environ is None else environ
    return Path(environ.get("XDG_CONFIG_HOME") or Path.home() / ".config") / "opencode" / "opencode.json"


class OpenCode:
    """OpenCode through the gateway's OpenAI Chat Completions API."""

    name = "opencode"

    def plugin(self, context: IntegrationContext) -> Path:
        """Write the plugin for this profile into the configuration folder and return its path."""
        if context.home is None:
            raise CredentialError("OpenCode needs the configuration folder for its plugin.")
        settings = {
            "cli": list(context.cli_command()), "profile": context.profile.name, "provider": PROVIDER,
            "baseURL": context.gateway.endpoint(Api.OPENAI_CHAT), "headers": list(context.labels.header_names()),
        }
        path = context.home / "opencode" / f"vkm-{context.profile.name}.js"
        path.parent.mkdir(parents=True, exist_ok=True)
        content = PLUGIN.replace("__SETTINGS__", json.dumps(settings))
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            atomic_write_text(path, content)
        return path

    def provider(self, context: IntegrationContext, models: list[str]) -> dict:
        return {
            "npm": "@ai-sdk/openai-compatible",
            "name": "vkm",
            # A placeholder: the plugin replaces the Authorization header on every request.
            "options": {"baseURL": context.gateway.endpoint(Api.OPENAI_CHAT), "apiKey": PLACEHOLDER_KEY},
            "models": {model: {"name": model} for model in models},
        }

    # Launch

    def command(
        self, context: IntegrationContext, attribution: Attribution | None, args: list[str], model: str | None,
        major: int = 1,
    ) -> tuple[list[str], dict[str, str]]:
        command = _opencode_command(args, major)
        if not model:
            raise CredentialError("OpenCode requires --model with a model alias available on the gateway.")
        if major == 2:
            return self._command_v2(context, attribution, args, model)
        attribution_headers(context, attribution)  # Fail now while required labels are missing.
        env = os.environ.copy()
        config = self._inline_config(env)
        config.setdefault("provider", {})[PROVIDER] = self.provider(context, [model])
        config["plugin"] = [*config.get("plugin", []), self.plugin(context).as_uri()]
        config["model"] = PROVIDER + "/" + model
        env["OPENCODE_CONFIG_CONTENT"] = json.dumps(config)
        env.pop(TOKEN_VARIABLE, None)
        set_launch_marker(env, attribution)  # The plugin passes it to 'repo show --launch'.
        return command, env

    def _command_v2(
        self, context: IntegrationContext, attribution: Attribution | None, args: list[str], model: str,
    ) -> tuple[list[str], dict[str, str]]:
        """OpenCode v2 cannot load the v1 plugin yet: a launch-time token and fixed headers, as before."""
        env = child_environment(context, attribution)
        config = self._inline_config(env)
        options = {"baseURL": context.gateway.endpoint(Api.OPENAI_CHAT), "apiKey": "{env:" + TOKEN_VARIABLE + "}"}
        headers = attribution_headers(context, attribution)
        if headers:
            options["headers"] = headers
        config.setdefault("provider", {})[PROVIDER] = {**self.provider(context, [model]), "options": options}
        config["model"] = PROVIDER + "/" + model
        env["OPENCODE_CONFIG_CONTENT"] = json.dumps(config)
        return _opencode_command(args, 2), env

    @staticmethod
    def _inline_config(env: dict[str, str]) -> dict:
        try:
            config = json.loads(env.get("OPENCODE_CONFIG_CONTENT", "{}"))
        except (ValueError, RecursionError):
            raise CredentialError("Existing OPENCODE_CONFIG_CONTENT is invalid JSON.") from None
        if (
            not isinstance(config, dict) or not isinstance(config.get("provider", {}), dict)
            or not isinstance(config.get("plugin", []), list)
        ):
            raise CredentialError("Existing OpenCode provider configuration is invalid.")
        return config

    def launch(
        self, context: IntegrationContext, attribution: Attribution | None, args: list[str], model: str | None,
    ) -> int:
        self.command(context, attribution, args, model)  # Validate before looking for the binary.
        executable = shutil.which("opencode")
        if executable is None:
            raise CredentialError("Install 'opencode' and make it available on PATH.")
        command, env = self.command(context, attribution, args, model, _opencode_major(executable))
        return execute(self.name, [executable, *command[1:]], env)

    # User-level setup

    def _models(self, context: IntegrationContext, model: str | None) -> list[str]:
        """The gateway's models (OpenAI-compatible model list), or just the given one if listing fails."""
        models = [model] if model else []
        try:
            models += [listed for listed in list_models(context.gateway, context.token) if listed not in models]
        except CredentialError:
            pass
        if not models:
            raise CredentialError("The gateway did not list its models; rerun setup with --model ALIAS.")
        return models

    def _read(self, path: Path) -> tuple[str | None, dict]:
        if not path.exists() and path.with_suffix(".jsonc").exists():
            raise CredentialError(f"{path.with_suffix('.jsonc')} uses comments; add the provider and plugin by hand.")
        try:
            original = path.read_text(encoding="utf-8")
        except FileNotFoundError:
            return None, {}
        except (OSError, UnicodeError):
            raise CredentialError(f"Cannot read {path}.") from None
        try:
            data = json.loads(original)
        except (ValueError, RecursionError):
            raise CredentialError(f"{path} is not plain JSON; fix it or add the provider and plugin by hand.") from None
        if (
            not isinstance(data, dict) or not isinstance(data.get("provider", {}), dict)
            or not isinstance(data.get("plugin", []), list)
        ):
            raise CredentialError(f"{path} has an invalid provider or plugin list; nothing was changed.")
        return original, data

    def _write(self, path: Path, data: dict, original: str | None) -> None:
        try:
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current != original:
                raise CredentialError(f"{path} changed while it was being updated; nothing was changed, retry.")
            permissions = path.stat().st_mode & 0o777 if path.exists() else None
            path.parent.mkdir(parents=True, exist_ok=True)
            atomic_write_text(path, json.dumps(data, indent=2) + "\n", permissions=permissions, follow_symlinks=True)
        except OSError:
            raise CredentialError(f"Cannot write {path}; nothing was changed.") from None

    def _ours(self, context: IntegrationContext, entry: object) -> bool:
        return isinstance(entry, str) and entry.startswith((context.home / "opencode").as_uri() + "/vkm-")

    def setup(self, context: IntegrationContext, model: str | None = None, replace: bool = False) -> list[str]:
        executable = shutil.which("opencode")
        if executable is not None and _opencode_major(executable) != 1:
            raise CredentialError("Setup supports OpenCode v1 plugins; use 'vkm run opencode' with v2.")
        path = config_path()
        original, data = self._read(path)
        if not replace and PROVIDER in data.get("provider", {}) and data["provider"][PROVIDER].get("name") != "vkm":
            raise CredentialError(f"{path} already has another provider named {PROVIDER}; rerun with --replace.")
        models = self._models(context, model)
        data.setdefault("provider", {})[PROVIDER] = self.provider(context, models)
        plugin = self.plugin(context).as_uri()
        data["plugin"] = [entry for entry in data.get("plugin", []) if not self._ours(context, entry)] + [plugin]
        notes = []
        if model and ("model" not in data or str(data["model"]).startswith(PROVIDER + "/")):
            data["model"] = f"{PROVIDER}/{model}"
        elif model:
            notes.append(f"Note: {path} already selects a model; choose '{PROVIDER}/{model}' in OpenCode.")
        self._write(path, data, original)
        return [
            f"Configured {path} for profile '{context.profile.name}' with {len(models)} model(s). "
            "OpenCode gets a fresh credential and the labels of its directory for every request; "
            "while required labels are missing, requests fail before they are sent.",
            *notes,
        ]

    def remove(self, context: IntegrationContext) -> list[str]:
        path = config_path()
        original, data = self._read(path)
        if original is None:
            return [f"{path} has no vkm configuration."]
        data.get("provider", {}).pop(PROVIDER, None)
        if not data.get("provider", True):
            del data["provider"]
        if "plugin" in data:
            data["plugin"] = [entry for entry in data["plugin"] if not self._ours(context, entry)]
            if not data["plugin"]:
                del data["plugin"]
        if str(data.get("model", "")).startswith(PROVIDER + "/"):
            del data["model"]
        self._write(path, data, original)
        return [f"Removed the vkm provider and plugin from {path}."]
